// Writes zp-cards.js, the one file HACS installs, from the card scripts in src/.
//
//   node scripts/build.js          write zp-cards.js
//   node scripts/build.js --check  exit 1 if zp-cards.js is out of date
//
// Each script goes in its own block. The scripts declare some of the same
// top-level names (esc, STRINGS, ...), and a block keeps each set private.
// That holds because the bundle loads as a module, so it is strict code and
// function declarations stay inside their block.

const fs = require("node:fs");
const path = require("node:path");

const SOURCES = ["budget-sankey-card.js", "prepping-cards.js"];
const root = path.join(__dirname, "..");
const out = path.join(root, "zp-cards.js");

function build() {
  const parts = SOURCES.map((name) => {
    const code = fs.readFileSync(path.join(root, "src", name), "utf8").trimEnd();
    return `// src/${name}\n{\n${code}\n}\n`;
  });
  return "// ZPCards: generated by scripts/build.js from src/. Edit src/, not this file.\n\n" + parts.join("\n");
}

const bundle = build();
if (process.argv.includes("--check")) {
  if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== bundle) {
    console.error("zp-cards.js is out of date: run node scripts/build.js");
    process.exit(1);
  }
} else {
  fs.writeFileSync(out, bundle);
}

module.exports = { build };
